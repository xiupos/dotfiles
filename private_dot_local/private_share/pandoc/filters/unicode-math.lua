-- Unicode ranges treated as "alphanumeric" for the spacing rule below,
-- approximating Haskell's Data.Char.isAlphaNum for the scripts that
-- actually show up in math text.
local function is_alpha_num(cp)
  if not cp then return false end
  if cp >= 0x30 and cp <= 0x39 then return true end -- ASCII digits
  if cp >= 0x41 and cp <= 0x5A then return true end -- ASCII upper
  if cp >= 0x61 and cp <= 0x7A then return true end -- ASCII lower
  if cp >= 0xC0 and cp <= 0x24F and cp ~= 0xD7 and cp ~= 0xF7 then
    return true -- Latin-1 Supplement / Latin Extended letters
  end
  if cp >= 0x370 and cp <= 0x3FF then return true end -- Greek and Coptic
  if cp >= 0x1F00 and cp <= 0x1FFF then return true end -- Greek Extended
  if cp >= 0x400 and cp <= 0x4FF then return true end -- Cyrillic
  if cp >= 0x2100 and cp <= 0x214F then return true end -- Letterlike Symbols
  if cp >= 0x1D400 and cp <= 0x1D7FF then
    return true -- Mathematical Alphanumeric Symbols
  end
  return false
end

-- Replace Unicode math symbols in a string by equivalent Latex commands,
-- inserting a space after an inserted command when the following character
-- is alphanumeric (e.g. "λx" -> "\lambda x", "λα" -> "\lambda \alpha").
local function unicode_to_latex(text)
  local codepoints = {}
  for _, cp in utf8.codes(text) do
    codepoints[#codepoints + 1] = cp
  end

  local out = {}
  for i, cp in ipairs(codepoints) do
    local ch = utf8.char(cp)
    local repl = symbols[ch]
    if repl then
      out[#out + 1] = repl
      if is_alpha_num(codepoints[i + 1]) then
        out[#out + 1] = " "
      end
    else
      out[#out + 1] = ch
    end
  end
  return table.concat(out)
end

function Math(el)
  el.text = unicode_to_latex(el.text)
  return el
end
