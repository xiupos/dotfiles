-- unicode-math.lua -- a Pandoc Lua filter that rewrites Unicode math
-- symbols inside Math nodes (e.g. "α", "⊗", "𝔸") into their LaTeX
-- command equivalents (e.g. "\alpha", "\otimes", "\mathbb{A}"), so that
-- documents written with Unicode math input compile under pdfLaTeX. A
-- space is inserted after an inserted command when the following
-- character is alphanumeric, to avoid TeX swallowing it into the
-- command name (e.g. "λx" -> "\lambda x").
--
-- The character-to-command table is derived from the symbol list of
-- the unicode-math LaTeX package (unicode-math-table.tex):
--   https://github.com/latex3/unicode-math/blob/master/unicode-math-table.tex
--   Copyright (c) 2006-2019  Will Robertson, LPPL "maintainer"
--   Copyright (c) 2010-2017  Philipp Stephani
--   Copyright (c) 2011-2017  Joseph Wright
--   Copyright (c) 2012-2015  Khaled Hosny
--   Distributed under the LaTeX Project Public License (LPPL), version
--   1.3c or later: <https://www.latex-project.org/lppl/>.
-- The specific set of characters was originally enumerated by
-- TANIGUCHI Masaya (2021) and extended by xiupos (2024). Where
-- unicode-math's own command names require the unicode-math package
-- itself (e.g. \BbbN, \mscrA, \mbfitA), this table instead maps to
-- plain commands usable with only amsmath/amssymb/mathtools/mathrsfs/bm
-- (e.g. \mathbb{N}, \mathscr{A}, \bm{A}), so the output works under
-- pdfLaTeX without loading unicode-math.
--
